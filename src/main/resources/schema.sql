-- Module-owned tables. IF NOT EXISTS preserves existing development data on restart.
CREATE TABLE IF NOT EXISTS fo_flight (
    id VARCHAR(255) PRIMARY KEY,
    version BIGINT,
    flight_number VARCHAR(255) NOT NULL,
    scheduled_departure_date DATE NOT NULL,
    departure_airport VARCHAR(255) NOT NULL,
    arrival_airport VARCHAR(255) NOT NULL,
    aircraft_registration VARCHAR(255) NOT NULL,
    scheduled_departure TIMESTAMP NOT NULL,
    scheduled_arrival TIMESTAMP NOT NULL,
    actual_departure TIMESTAMP,
    actual_arrival TIMESTAMP,
    final_load_received BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS fo_delay (
    flight_id VARCHAR(255) REFERENCES fo_flight(id),
    delay_id UUID PRIMARY KEY,
    code VARCHAR(255) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    minutes INTEGER NOT NULL,
    phase VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS pm_message (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id UUID NOT NULL UNIQUE,
    source_event_id UUID NOT NULL,
    produced_at TIMESTAMP NOT NULL,
    format_version INTEGER NOT NULL,
    flight_key VARCHAR(255) NOT NULL,
    flight_number VARCHAR(255) NOT NULL,
    scheduled_departure_date DATE NOT NULL,
    departure_airport VARCHAR(255) NOT NULL,
    kind VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    UNIQUE (source_event_id, kind)
);
CREATE TABLE IF NOT EXISTS oc_policy (
    id INTEGER PRIMARY KEY,
    version BIGINT,
    offloading_constraint VARCHAR(255) NOT NULL,
    loading_window_opening_minutes INTEGER NOT NULL,
    loading_window_closing_minutes INTEGER NOT NULL,
    maximum_lateral_weight_difference_percent NUMERIC(19,6) NOT NULL,
    flight_retention_days INTEGER NOT NULL,
    actual_time_tolerance_minutes INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS oc_feed_receipt (message_id UUID PRIMARY KEY);

-- Spring Modulith 2.x Event Publication Registry (as in Piggybank's SQL schema).
-- Hibernate's default VARCHAR(255) is too short for event payloads: use TEXT.
CREATE TABLE IF NOT EXISTS event_publication (
    id UUID PRIMARY KEY,
    listener_id TEXT NOT NULL,
    event_type TEXT NOT NULL,
    serialized_event TEXT NOT NULL,
    publication_date TIMESTAMP WITH TIME ZONE NOT NULL,
    completion_date TIMESTAMP WITH TIME ZONE,
    status TEXT,
    completion_attempts INTEGER,
    last_resubmission_date TIMESTAMP WITH TIME ZONE
);
